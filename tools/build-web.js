#!/usr/bin/env node
// Builds the web dashboard (backend/web) from the extension's dashboard, so it opens in any browser, phone included.
// Run after changing extension/dashboard, extension/ui or extension/shared.js:  node tools/build-web.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const ext = path.join(root, 'extension');
const out = path.join(root, 'backend', 'web');
const version = JSON.parse(fs.readFileSync(path.join(ext, 'manifest.json'), 'utf8')).version;

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'icons'), { recursive: true });

const copy = (from, to) => fs.copyFileSync(path.join(ext, from), path.join(out, to));
copy('dashboard/dashboard.css', 'dashboard.css');
copy('dashboard/dashboard.js', 'dashboard.js');
copy('ui/base.css', 'base.css');
copy('config.js', 'config.js');
copy('brand.js', 'brand.js');
copy('shared.js', 'shared.js');
copy('icons/icon128.png', 'icons/icon128.png');
copy('icons/icon48.png', 'icons/icon48.png');

// The dashboard was written for the extension. This stands in for the few chrome.* calls it makes.
fs.writeFileSync(path.join(out, 'chrome-shim.js'), `// Generated by tools/build-web.js. Lets the extension's dashboard run as a normal web page.
(() => {
  document.documentElement.dataset.web = '1';
  const listeners = [];
  const read = () => { try { return JSON.parse(localStorage.getItem('openly:store') || '{}'); } catch { return {}; } };
  const write = (o) => { try { localStorage.setItem('openly:store', JSON.stringify(o)); } catch { /* private mode */ } };
  const pick = (all, keys) => {
    if (keys == null) return { ...all };
    if (typeof keys === 'string') keys = [keys];
    const out = {};
    if (Array.isArray(keys)) keys.forEach((k) => { if (k in all) out[k] = all[k]; });
    else Object.entries(keys).forEach(([k, d]) => { out[k] = k in all ? all[k] : d; });
    return out;
  };
  const fire = (changes) => listeners.forEach((fn) => { try { fn(changes, 'local'); } catch { /* ignore */ } });
  globalThis.chrome = {
    storage: {
      local: {
        async get(keys) { return pick(read(), keys); },
        async set(obj) {
          const all = read(); const changes = {};
          for (const [k, v] of Object.entries(obj)) { changes[k] = { oldValue: all[k], newValue: v }; all[k] = v; }
          write(all); fire(changes);
        },
        async remove(keys) {
          const all = read(); const changes = {};
          for (const k of [].concat(keys)) { if (k in all) { changes[k] = { oldValue: all[k] }; delete all[k]; } }
          write(all); fire(changes);
        },
      },
      onChanged: { addListener: (fn) => listeners.push(fn) },
    },
    runtime: { id: 'web', sendMessage: () => Promise.resolve({ ok: true }), getManifest: () => ({ version: '${version} (web)' }), getURL: (p) => p },
    notifications: { create() {} },
  };
})();
`);

let html = fs.readFileSync(path.join(ext, 'dashboard/dashboard.html'), 'utf8');
html = html
  .replace('../ui/base.css', 'base.css')
  .replace('<script src="../config.js"></script>', '<script src="chrome-shim.js"></script>\n<script src="config.js"></script>')
  .replace('../brand.js', 'brand.js')
  .replace('../shared.js', 'shared.js')
  .replace(/\s*<script src="\.\.\/vendor\/qrcode\.js"><\/script>/, '')
  .replace('<title>Openly</title>', '<title>Openly</title>\n  <meta name="theme-color" content="#0B8F6A">\n  <link rel="manifest" href="manifest.webmanifest">\n  <link rel="icon" href="icons/icon48.png">\n  <link rel="apple-touch-icon" href="icons/icon128.png">');
// Scripts and styles are referenced by content hash, so the server can let browsers keep them for a year.
const crypto = require('crypto');
for (const f of ['base.css', 'dashboard.css', 'chrome-shim.js', 'config.js', 'brand.js', 'shared.js', 'dashboard.js']) {
  const hash = crypto.createHash('sha1').update(fs.readFileSync(path.join(out, f))).digest('hex').slice(0, 10);
  html = html.replace(new RegExp(`((?:src|href)=")${f.replace('.', '\\.')}"`), `$1${f}?v=${hash}"`);
}
fs.writeFileSync(path.join(out, 'index.html'), html);

fs.writeFileSync(path.join(out, 'manifest.webmanifest'), JSON.stringify({
  name: 'Openly', short_name: 'Openly', start_url: './', scope: './', display: 'standalone',
  background_color: '#ffffff', theme_color: '#0B8F6A',
  icons: [{ src: 'icons/icon48.png', sizes: '48x48', type: 'image/png' }, { src: 'icons/icon128.png', sizes: '128x128', type: 'image/png' }],
}, null, 2));

console.log('Web dashboard written to backend/web');
